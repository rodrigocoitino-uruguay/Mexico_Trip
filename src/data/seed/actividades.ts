import type { Actividad } from '../../domain/types';
import { base } from './util';

type A = Omit<Actividad, 'id' | 'diaId' | 'orden' | 'estado' | 'updatedAt' | 'delSeed'>;

/** Arma las actividades de un día con id estable: '2027-02-13-03'. */
function dia(diaId: string, items: A[]): Actividad[] {
  return items.map((a, i) => ({
    ...base(`${diaId}-${String(i + 1).padStart(2, '0')}`),
    diaId,
    orden: (i + 1) * 10,
    estado: 'pendiente',
    ...a,
  }));
}

